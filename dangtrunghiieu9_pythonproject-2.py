#1. Tạo frame
import streamlit as st
import pandas as pd
import matplotlib.pyplot as plt

data = {
    "Ho_ten": [
        "An", "Anh", "Chi", "Dung", "Hoang",
        "Huy", "Hieu", "Phuong", "Tran", "Vu"
    ],
    "Chuyen_can": [7, 7, 9, 8, 7, 8, 8, 9, 9, 7],
    "Giua_ky": [6, 7, 8, 8, 6, 8, 8, 9, 8, 7],
    "Cuoi_ky": [7, 8, 8, 7, 6, 8, 9, 10, 9, 8]
}
df = pd.DataFrame(data)

st.dataframe(df)

#2.Tính điểm tổng kết
df["Tong_ket"] = (
    0.2 * df["Chuyen_can"]
    + 0.3 * df["Giua_ky"]
    + 0.5 * df["Cuoi_ky"]
)
st.dataframe(df)

#3. Xếp loại
def xep_loai(diem):
    if diem >= 8.5:
        return "Giỏi"
    elif diem >= 7:
        return "Khá"
    elif diem >= 5:
        return "Trung bình"
    else:
        return "Yếu"
df["Xep_loai"] = df["Tong_ket"].apply(xep_loai)
st.dataframe(df)

#4. Thống kê

trung_binh = df["Tong_ket"].mean()
cao_nhat = df["Tong_ket"].max()

sinh_vien_cao_nhat = df.loc[
    df["Tong_ket"].idxmax()
]

sinh_vien_thap_nhat = df.loc[
    df["Tong_ket"].idxmin()
]

so_sinh_vien_dat = (df["Tong_ket"] >= 5).sum()

print(f"Trung bình: {trung_binh}")
print(f"Cao nhất: {cao_nhat}")

print("Sinh viên cao nhất:")
st.dataframe(sinh_vien_cao_nhat.to_frame().T)

print("Sinh viên thấp nhất:")
st.dataframe(sinh_vien_thap_nhat.to_frame().T)

print(f"Số sinh viên đạt: {so_sinh_vien_dat}")

print(df)

#5. Trực quan hoá
import matplotlib.pyplot as plt

fig = plt.figure(figsize=(10, 5))

plt.bar(df["Ho_ten"], df["Tong_ket"])

plt.title("Điểm tổng kết của 10 sinh viên")
plt.xlabel("Họ và tên sinh viên")
plt.ylabel("Điểm tổng kết")
plt.ylim(0, 10)
plt.xticks(rotation=45, ha='right')
plt.tight_layout()
plt.savefig("bieu_do_diem.png", dpi=300)

st.pyplot(fig)

